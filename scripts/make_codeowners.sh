#!/usr/bin/env bash
# Write .github/CODEOWNERS from scripts/owners.txt, so GitHub asks each
# component's owner to review changes to their files (and the lead for the
# contracts). Run it after filling in owners.txt, then commit the result.
set -euo pipefail
cd "$(dirname "$0")/.."
owner() { awk -v c="$1" '$1 == c && NF >= 2 { print "@" $2 }' scripts/owners.txt; }
lead="$(owner LEAD)"
[[ -n "$lead" ]] || { echo "fill in scripts/owners.txt first (at least LEAD)"; exit 1; }
{
  echo "# Generated by scripts/make_codeowners.sh from scripts/owners.txt. Don't edit by hand."
  echo "# The last matching line wins."
  echo "*                         $lead"
  for c in conn http pool app wal snap vec kw cli load; do
    o="$(owner "$(echo $c | tr a-z A-Z)")"
    [[ -n "$o" ]] && echo "/src/$c/                   $o"
    [[ -n "$o" ]] && echo "/tests/unit/$c/            $o"
  done
  echo "/include/forge/           $lead"
  echo "/tests/contract/          $lead"
  echo "/tests/support/           $lead"
  echo "/docs/API.md              $lead"
  echo "/docs/FORMAT.md           $lead"
  o="$(owner APP)";  [[ -n "$o" ]] && echo "/apps/forgedb.cpp         $o"
  o="$(owner CLI)";  [[ -n "$o" ]] && echo "/apps/forge.cpp           $o" && echo "/clients/                 $o"
  o="$(owner LOAD)"; [[ -n "$o" ]] && echo "/apps/forge_load.cpp      $o"
  o="$(owner HTTP)"; [[ -n "$o" ]] && echo "/fuzz/                    $o"
} > .github/CODEOWNERS
echo "wrote .github/CODEOWNERS:"
cat .github/CODEOWNERS
